export function getSchemesForMessage(message) {
  const lower = message.toLowerCase();
  if (lower.match(/farmer|kisan|agriculture|crop|kheti|fasal|खेती|किसान|फसल/))
    return MOCK_SCHEMES.agriculture;
  if (lower.match(/health|hospital|ayushman|medical|doctor|insurance|स्वास्थ्य|अस्पताल/))
    return MOCK_SCHEMES.health;
  if (lower.match(/education|student|scholarship|school|college|study|पढ़ाई|शिक्षा|छात्रवृत्ति/))
    return MOCK_SCHEMES.education;
  if (lower.match(/house|home|housing|pmay|ghar|मकान|घर/))
    return MOCK_SCHEMES.housing;
  if (lower.match(/business|loan|msme|startup|shop|व्यवसाय|दुकान/))
    return MOCK_SCHEMES.business;
  if (lower.match(/job|skill|training|employment|work|rojgar|नौकरी|रोजगार|कौशल/))
    return MOCK_SCHEMES.employment;
  return [];
}
